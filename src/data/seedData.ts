const buildTasksFromRequirements = (
  requirements: Requirement[],
  members: string[],
  doneCount: number,
  dueDate = "2026-12-20"
): Task[] =>
  requirements
    .filter((item) => item.priority === "must")
    .map((requirement, index) => {
      const guide = getDefaultTaskGuide(requirement.title, requirement.id);
      return {
        id: `task-${index + 1}`,
        requirementId: requirement.id,
        title: requirement.title,
        howToSteps: guide.howToSteps,
        acceptanceCriteria: guide.acceptanceCriteria,
        assigneeName: members[index % Math.max(members.length, 1)] ?? "",
        status: index < doneCount ? "done" : "todo",
        priority: index < 2 ? "high" : "medium",
        dueDate,
      };
    });

